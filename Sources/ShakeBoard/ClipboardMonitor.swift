//
//  ClipboardMonitor.swift
//  ShakeBoard -- clipboard capture: change detection, secret filtering, bounded snapshotting, and the ONE
//  tagged writer every ShakeBoard pasteboard write must go through.
//
//  Design: one watcher powers both clipboard history and paste-stack collection.
//  - NSPasteboard has no change notification, so a cheap changeCount check runs on a common-modes
//    timer (keeps firing during menu tracking). Only a CHANGE triggers a read.
//  - A read is a snapshot: read the allow-listed types, then re-check changeCount; if it moved
//    mid-read the snapshot is discarded and the next tick picks up the newer contents.
//  - Heavy work (hashing, TIFF->PNG, sidecar writes) runs off main on ClipStore's serial queue.
//  - Skips: ShakeBoard's own writes (marker type), nspasteboard.org Concealed/Transient/AutoGenerated
//    markers, known password-manager apps, and anything copied while Secure Input is on. This is a
//    best-effort filter, NOT a guarantee that no secret is ever stored.
//

import AppKit
import Carbon   // IsSecureEventInputEnabled

// MARK: - Pasteboard access (injectable so tests never touch NSPasteboard.general)

struct RawRep: Equatable {
    let type: String
    let data: Data
}

struct RawSnapshot: Equatable {
    let changeCount: Int
    let allTypes: Set<String>      // every type present on the pasteboard (for marker checks)
    let items: [[RawRep]]          // ordered items, each with its ordered allow-listed reps
}

protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    // Read only `allowed` types, at most `maxItems` items, skipping any single rep over `maxRepBytes`.
    func readSnapshot(allowed: [String], maxItems: Int, maxRepBytes: Int) -> RawSnapshot
    // Replace the pasteboard contents with `items` (each an ordered list of reps). Returns the new
    // changeCount so callers can later tell whether the pasteboard is still theirs.
    @discardableResult func write(_ items: [[RawRep]]) -> Int
    var types: Set<String> { get }
    // EVERY readable type of every item (markers included) -- used to save the user's original clipboard
    // before the paste stack takes it over, so restore is faithful. Unreadable/oversized reps are skipped;
    // stops once `maxTotalBytes` would be exceeded.
    func readAll(maxItems: Int, maxRepBytes: Int, maxTotalBytes: Int) -> [[RawRep]]
}

final class SystemPasteboard: PasteboardAccess {
    private let pb: NSPasteboard
    init(_ pb: NSPasteboard = .general) { self.pb = pb }

    var changeCount: Int { pb.changeCount }
    var types: Set<String> { Set((pb.types ?? []).map(\.rawValue)) }

    func readSnapshot(allowed: [String], maxItems: Int, maxRepBytes: Int) -> RawSnapshot {
        let count = pb.changeCount
        let all = types
        var items: [[RawRep]] = []
        for item in (pb.pasteboardItems ?? []).prefix(maxItems) {
            var reps: [RawRep] = []
            let present = Set(item.types.map(\.rawValue))
            for t in allowed where present.contains(t) {
                guard let d = item.data(forType: NSPasteboard.PasteboardType(t)) else { continue }
                guard d.count <= maxRepBytes else { continue }   // oversized rep -- drop it, keep the rest
                reps.append(RawRep(type: t, data: d))            // Data is a value copy: no lazy owner
            }
            if !reps.isEmpty { items.append(reps) }
        }
        return RawSnapshot(changeCount: count, allTypes: all, items: items)
    }

    func readAll(maxItems: Int, maxRepBytes: Int, maxTotalBytes: Int) -> [[RawRep]] {
        var total = 0
        var out: [[RawRep]] = []
        for item in (pb.pasteboardItems ?? []).prefix(maxItems) {
            var reps: [RawRep] = []
            for t in item.types {
                guard let d = item.data(forType: t), d.count <= maxRepBytes, total + d.count <= maxTotalBytes else { continue }
                total += d.count
                reps.append(RawRep(type: t.rawValue, data: d))
            }
            if !reps.isEmpty { out.append(reps) }
        }
        return out
    }

    @discardableResult
    func write(_ items: [[RawRep]]) -> Int {
        pb.clearContents()
        let objs: [NSPasteboardItem] = items.enumerated().map { idx, reps in
            let it = NSPasteboardItem()
            for r in reps { it.setData(r.data, forType: NSPasteboard.PasteboardType(r.type)) }
            if idx == 0 {
                // Tag every ShakeBoard write so the monitor (and other well-behaved managers) can skip it.
                it.setData(Data(), forType: NSPasteboard.PasteboardType(ClipTypes.shakeboardMarker))
            }
            return it
        }
        if !objs.isEmpty { pb.writeObjects(objs) }
        return pb.changeCount
    }
}

// MARK: - Type vocabulary

enum ClipTypes {
    static let shakeboardMarker = "com.thisradlife.shakeboard.self"
    static let legacyPerchMarker = "com.dadequate.perch.self"
    static let plainText = "public.utf8-plain-text"
    static let rtf = "public.rtf"
    static let html = "public.html"
    static let png = "public.png"
    static let tiff = "public.tiff"
    static let fileURL = "public.file-url"
    static let url = "public.url"

    // Order matters: it is the order reps are written back (richest text first is what apps expect).
    static let allowed: [String] = [fileURL, url, rtf, html, plainText, png, tiff]

    // nspasteboard.org conventions -- apps that hold secrets (password managers) or transient junk set these.
    static let secretMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",      // 1Password 7 legacy marker
    ]

    // Known password managers: skip anything copied while one is frontmost, marker or not.
    static let ignoredBundleIDs: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords",
        "net.antelle.keeweb", "org.keepassxc.keepassxc", "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal", "com.dashlane.Dashlane", "in.sinew.Enpass-Desktop",
        "com.nordsec.nordpass", "com.ttm.TypeIt4Me",
    ]
}

enum ClipLimits {
    static let maxItemsPerClip = 20
    static let maxRepBytes = 20 * 1024 * 1024          // a single representation (any type)
    static let maxTextBytes = 1 * 1024 * 1024          // plain text
    static let maxRichTextBytes = 2 * 1024 * 1024      // RTF / HTML
    static var maxImagePixels = 50_000_000             // decoded size guard (~200 MB RGBA); var for tests
    static let pollInterval: TimeInterval = 0.5
}

// MARK: - Filtering (pure, testable)

enum ClipSkipReason: Equatable {
    case shakeboardWrite, secretMarker, ignoredApp, secureInput, empty, disabled, unstable
}

enum ClipFilter {
    static func skipReason(types: Set<String>, bundleID: String?, secureInput: Bool,
                           ignored: Set<String> = ClipTypes.ignoredBundleIDs) -> ClipSkipReason? {
        if types.contains(ClipTypes.shakeboardMarker) || types.contains(ClipTypes.legacyPerchMarker) { return .shakeboardWrite }
        if !types.isDisjoint(with: ClipTypes.secretMarkers) { return .secretMarker }
        if let bundleID, ignored.contains(bundleID) { return .ignoredApp }
        if secureInput { return .secureInput }
        return nil
    }
}

// MARK: - Monitor

// Snapshot handed to the store for off-main normalization.
struct CapturedClipboard {
    let snapshot: RawSnapshot
    let sourceBundleID: String?
    let sourceAppName: String?
    let capturedAt: Date
}

@MainActor
final class ClipboardMonitor {
    private let pasteboard: PasteboardAccess
    private let secureInput: () -> Bool
    private let frontmost: () -> (bundleID: String?, name: String?)
    private let clock: () -> Date
    private var lastCount: Int
    private var timer: Timer?
    var isEnabled = true
    // Apps the user added in Settings > Clipboard, skipped on top of the built-in password managers.
    var extraIgnored: () -> Set<String> = { [] }
    // Apps that were frontmost at some point since the last poll (fed by deactivation). A copy is attributed
    // to EVERY one of them for the ignore check, so copying in an ignored app and switching away before the
    // 0.5 s poll can't save it (fail closed).
    private var activeSinceTick: Set<String> = []
    private var deactivationObserver: Any?
    func noteDeactivated(bundleID: String?) { if let bundleID { activeSinceTick.insert(bundleID) } }
    var onCapture: ((CapturedClipboard) -> Void)?

    init(pasteboard: PasteboardAccess,
         secureInput: @escaping () -> Bool = { IsSecureEventInputEnabled() },
         frontmost: @escaping () -> (bundleID: String?, name: String?) = {
             let app = NSWorkspace.shared.frontmostApplication
             return (app?.bundleIdentifier, app?.localizedName)
         },
         clock: @escaping () -> Date = Date.init) {
        self.pasteboard = pasteboard
        self.secureInput = secureInput
        self.frontmost = frontmost
        self.clock = clock
        // Start from the CURRENT count: whatever is on the clipboard at launch was copied before ShakeBoard
        // was watching and is not a new copy.
        self.lastCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        deactivationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didDeactivateApplicationNotification, object: nil, queue: .main) { [weak self] n in
            let app = n.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            MainActor.assumeIsolated { self?.noteDeactivated(bundleID: app?.bundleIdentifier) }
        }
        let t = Timer(timeInterval: ClipLimits.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(t, forMode: .common)   // keep polling while a menu is tracking
        timer = t
    }
    func stop() {
        timer?.invalidate(); timer = nil
        if let deactivationObserver { NSWorkspace.shared.notificationCenter.removeObserver(deactivationObserver) }
        deactivationObserver = nil
    }

    // Treat the current pasteboard as already seen (used after ShakeBoard writes, belt-and-braces with the marker).
    func markSeen() { lastCount = pasteboard.changeCount; activeSinceTick = [] }
    // True when the user copied something the poll hasn't read yet.
    var hasUnseenChange: Bool { pasteboard.changeCount != lastCount }

    static let debug = ProcessInfo.processInfo.environment["PERCH_DEBUG_CLIPS"] != nil
    private(set) var lastSkip: ClipSkipReason? {
        didSet { if Self.debug, let lastSkip { NSLog("ShakeBoard clips: skipped (\(lastSkip))") } }
    }

    // One poll step. Internal (not private) so tests can drive it without a run loop.
    func tick() {
        let count = pasteboard.changeCount
        let recentlyActive = activeSinceTick
        activeSinceTick = []
        guard count != lastCount else { return }
        if Self.debug { NSLog("ShakeBoard clips: change \(lastCount) -> \(count) types=\(pasteboard.types.sorted())") }
        lastCount = count
        guard isEnabled else { lastSkip = .disabled; return }
        let front = frontmost()
        let ignored = ClipTypes.ignoredBundleIDs.union(extraIgnored())
        if !recentlyActive.isDisjoint(with: ignored) { lastSkip = .ignoredApp; return }
        if let reason = ClipFilter.skipReason(types: pasteboard.types, bundleID: front.bundleID,
                                              secureInput: secureInput(), ignored: ignored) {
            lastSkip = reason
            return
        }
        let snap = pasteboard.readSnapshot(allowed: ClipTypes.allowed,
                                           maxItems: ClipLimits.maxItemsPerClip,
                                           maxRepBytes: ClipLimits.maxRepBytes)
        // Re-check: if the pasteboard changed while we read, this snapshot may mix two copies. Drop it;
        // the next tick sees the newer count and reads it cleanly.
        guard pasteboard.changeCount == snap.changeCount, snap.changeCount == count else {
            lastSkip = .unstable
            lastCount = -1   // force the next tick to re-read
            activeSinceTick.formUnion(recentlyActive)   // ...still attributing it to every app seen since
            return
        }
        // Markers can appear on the snapshot even if the first types check raced; check again.
        if let reason = ClipFilter.skipReason(types: snap.allTypes, bundleID: front.bundleID,
                                              secureInput: false, ignored: ignored) {
            lastSkip = reason
            return
        }
        guard !snap.items.isEmpty else { lastSkip = .empty; return }
        lastSkip = nil
        onCapture?(CapturedClipboard(snapshot: snap, sourceBundleID: front.bundleID,
                                     sourceAppName: front.name, capturedAt: clock()))
    }
}

// MARK: - The one writer

// Every ShakeBoard write to the general pasteboard goes through here so it carries the marker (and the
// monitor never records ShakeBoard's own writes as new copies).
@MainActor
enum ClipboardWriter {
    static var pasteboard: PasteboardAccess = SystemPasteboard()
    static weak var monitor: ClipboardMonitor?

    static let maxPendingCaptureAttempts = 3

    // Returns the pasteboard changeCount after the write, or nil if the write was REFUSED because a copy
    // the poll hasn't recorded yet couldn't be captured (the pasteboard kept changing under the read).
    // Never overwrite an unrecorded copy: callers treat nil as "not written" (the stack pauses).
    @discardableResult
    static func write(_ items: [[RawRep]]) -> Int? {
        if let monitor {
            // Capture any pending copy synchronously to completion first. tick() re-arms itself when a read
            // was unstable (count moved mid-read), so retry a few times; a skip (secret, ignored app) also
            // counts as handled -- the monitor has made its decision about that copy.
            var attempts = 0
            while monitor.hasUnseenChange && attempts < maxPendingCaptureAttempts {
                monitor.tick(); attempts += 1
            }
            if monitor.hasUnseenChange {
                NSLog("ShakeBoard: write refused -- clipboard still changing, pending copy not recorded yet")
                return nil
            }
        }
        let c = pasteboard.write(items)
        monitor?.markSeen()
        return c
    }
    @discardableResult
    static func writeString(_ s: String) -> Int? {
        write([[RawRep(type: ClipTypes.plainText, data: Data(s.utf8))]])
    }
}
